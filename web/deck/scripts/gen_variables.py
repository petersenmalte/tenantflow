"""Generates web/deck/_variables.yml from bench/results (no numbers typed by hand).

Quarto reads _variables.yml; slides use {{< var fuzz.tenantflow.any >}} etc.
Usage: python3 web/deck/scripts/gen_variables.py  (stdlib only; ``--check`` fails if files are stale)
"""
# ruff: noqa: E501

from __future__ import annotations

import json
import sys
from pathlib import Path

DECK = Path(__file__).resolve().parents[1]
RES = DECK.parents[1] / "bench" / "results"
VARIANTS = ["none", "cedar-only", "fides", "tenantflow"]


def pct(x: float) -> str:
    return f"{100 * x:.1f} %".replace(".0 %", " %")


def build() -> str:
    r = json.loads((RES / "results.json").read_text())
    v: dict[str, dict] = {
        "meta": {k: r["meta"][k] for k in ("date", "git", "seed", "episodes", "episode_length")}
    }
    v["meta"]["date"] = r["meta"]["date"][:10]
    for suite in ("leak", "forgery", "utility"):
        v[suite] = {}
        for m in VARIANTS:
            e = r[suite][m]
            v[suite][m.replace("-", "_")] = {"rate": pct(e["rate"]), "kn": f"{e['k']}/{e['n']}"}
    v["fuzz"] = {}
    for m in VARIANTS:
        e = r["fuzz"][m]
        v["fuzz"][m.replace("-", "_")] = {
            "any": pct(e["any"]["rate"]),
            "anyk": f"{e['any']['k']}/{e['episodes']}",
            "ci": f"[{pct(e['any']['ci95'][0])}, {pct(e['any']['ci95'][1])}]",
        }
    v["latency"] = {
        m.replace("-", "_"): {
            "p50": f"{r['latency'][m]['p50_us']:.0f}",
            "p99": f"{r['latency'][m]['p99_us']:.0f}",
        }
        for m in VARIANTS
    }
    mo = r["latency_monitor_only"]
    v["monitor_only"] = {"p50": f"{mo['p50_us']:.1f}", "p99": f"{mo['p99_us']:.1f}"}
    return (
        "# generated by scripts/gen_variables.py from bench/results/results.json; do not edit\n"
        + dump(v)
    )


def dump(x, ind=0) -> str:
    pad = "  " * ind
    out = []
    for k, val in x.items():
        if isinstance(val, dict):
            out.append(f"{pad}{k}:\n{dump(val, ind + 1)}")
        else:
            out.append(f'{pad}{k}: "{val}"\n')
    return "".join(out)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        stale = (DECK / "_variables.yml").read_text() != text
        print("stale" if stale else "up to date")
        return 1 if stale else 0
    (DECK / "_variables.yml").write_text(text)
    print("wrote _variables.yml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
