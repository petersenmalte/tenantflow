// Writes src/theorems.js: Lean theorem name -> GitHub link with line anchor, scanned from lean/TenantFlow.
// `node scripts/gen_theorems.js --check` fails if the file is stale (run by tests/theorems.test.js).
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "../../..");
const REPO = "https://github.com/petersenmalte/tenantflow/blob/main/";

function scan() {
  const out = {};
  const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(path.join(dir, e.name)) : e.name.endsWith(".lean") ? [path.join(dir, e.name)] : []);
  for (const file of walk(path.join(ROOT, "lean/TenantFlow")).sort()) {
    const rel = path.relative(ROOT, file).split(path.sep).join("/");
    let ns = [];
    fs.readFileSync(file, "utf8").split("\n").forEach((line, i) => {
      let m;
      if ((m = /^namespace\s+(\S+)/.exec(line))) ns.push(m[1]);
      else if ((m = /^end\s+(\S+)/.exec(line)) && ns.length && ns[ns.length - 1] === m[1]) ns.pop();
      else if ((m = /^theorem\s+(\S+)/.exec(line))) {
        const full = [...ns, m[1]].join(".").replace(/^TenantFlow\./, "");
        out[full] = REPO + rel + "#L" + (i + 1);
      }
    });
  }
  return out;
}
const text = "// generated by scripts/gen_theorems.js; do not edit\n(function (root) {\n  const THEOREMS = " +
  JSON.stringify(scan(), null, 2).replace(/\n/g, "\n  ") +
  ";\n  if (typeof module !== \"undefined\" && module.exports) module.exports = { THEOREMS };\n" +
  "  else root.TF = Object.assign(root.TF || {}, { THEOREMS });\n})(typeof globalThis !== \"undefined\" ? globalThis : this);\n";
const target = path.join(__dirname, "../src/theorems.js");
if (process.argv.includes("--check")) {
  const ok = fs.existsSync(target) && fs.readFileSync(target, "utf8") === text;
  console.log(ok ? "up to date" : "stale: run node scripts/gen_theorems.js");
  process.exit(ok ? 0 : 1);
}
fs.writeFileSync(target, text);
console.log("wrote", Object.keys(scan()).length, "theorems");
