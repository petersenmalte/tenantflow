const test = require("node:test");
const assert = require("node:assert");
const fs = require("fs"), path = require("path");
const M = require("../src/monitor.js");
const L = require("../src/levels.js");
const R = require("../src/rules.js");

const plain = (x) => JSON.parse(JSON.stringify(x));
const norm = (out) => plain({ decisions: out.decisions, final: out.final });
const ORACLE_TESTS = path.join(__dirname, "../../../lean/Oracle/tests");

// 1. The five hand-written Lean oracle traces: exact equality with `lake exe oracle` output.
for (const f of fs.readdirSync(ORACLE_TESTS).filter((n) => /^t.*\.json$/.test(n))) {
  test("oracle trace " + f, () => {
    const sc = JSON.parse(fs.readFileSync(path.join(ORACLE_TESTS, f)));
    const expected = JSON.parse(fs.readFileSync(path.join(ORACLE_TESTS, f.replace(/\.json$/, ".expected.out"))));
    assert.deepStrictEqual(norm(M.runScenario(sc, "tenantflow")), expected);
  });
}

// 2. The scripted attacks of the levels, all four modes, against reference outputs generated by
//    scripts/gen_expected.py (TenantFlow = Lean oracle, the others = Python baselines).
const scenarios = JSON.parse(fs.readFileSync(path.join(__dirname, "fixtures/scenarios.json")));
const expected = JSON.parse(fs.readFileSync(path.join(__dirname, "fixtures/expected.json")));
for (const { id, scenario } of scenarios)
  for (const mode of M.MODES)
    test(`${id} / ${mode} agrees with the reference`, () => {
      assert.deepStrictEqual(norm(M.runScenario(scenario, mode)), expected[id][mode]);
    });

test("fixtures are up to date with levels.js", () => {
  const fresh = L.LEVELS.filter((l) => l.solution.length).map((l) => ({ id: "level" + l.id, scenario: plain(L.withTrace(l, l.solution)) }));
  assert.deepStrictEqual(fresh, scenarios);
});

// 3. Expected game outcome: every scripted attack wins in off / Cedar-only / FIDES where intended, never in TenantFlow.
const WINS = { // level -> modes in which the scripted attack must win
  1: ["none"], 2: ["none", "cedar-only", "fides"], 3: ["none", "cedar-only", "fides"], 4: ["none", "cedar-only", "fides"],
};
for (const lv of L.LEVELS.filter((l) => l.solution.length))
  for (const mode of M.MODES)
    test(`level ${lv.id} / ${mode}: attack ${WINS[lv.id].includes(mode) ? "wins" : "fails"}`, () => {
      const { monitor, decisions } = M.runScenario(L.withTrace(lv, lv.solution), mode);
      const log = lv.solution.map((s, i) => ({ ...s, response: decisions[i].response }));
      assert.strictEqual(R.won(lv.goal, monitor, log), WINS[lv.id].includes(mode));
    });

// 4. Fuzzer (level 5 sandbox): finds a leak without TenantFlow, none with it; shrunk sequence replays.
const sandbox = L.LEVELS[4].scenario;
test("fuzzer finds violations without TenantFlow", () => {
  for (const mode of ["none", "cedar-only", "fides"]) {
    const found = R.fuzz(sandbox, mode, "violation", { seed: 1, episodes: 300 });
    assert.ok(found, mode);
    assert.ok(found.steps.length <= 4, `${mode}: shrunk to ${found.steps.length}`);
    assert.ok(R.replay(sandbox, mode, found.steps, "violation").won);
  }
});
test("fuzzer finds nothing against TenantFlow", () => {
  for (const seed of [1, 2, 3]) assert.strictEqual(R.fuzz(sandbox, "tenantflow", "violation", { seed, episodes: 500 }), null);
});
test("fuzzer finds nothing against TenantFlow under an allow-all policy", () => {
  const sc = { ...sandbox, cedar: "allow_all" };
  assert.strictEqual(R.fuzz(sc, "tenantflow", "violation", { seed: 7, episodes: 1000 }), null);
});
